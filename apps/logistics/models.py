from django.conf import settings
from django.core.validators import MinValueValidator
from django.db import models
from django.utils import timezone

from apps.common.money import ZERO


class Courier(models.Model):
    """A last-mile delivery company that collects cash on behalf of merchants."""

    name = models.CharField(max_length=120, unique=True)
    code = models.SlugField(max_length=40, unique=True, help_text="Short code, e.g. 'speedex'.")
    contact_phone = models.CharField(max_length=30, blank=True)
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["name"]

    def __str__(self) -> str:
        return self.name


class Currency(models.TextChoices):
    MAD = "MAD", "Moroccan dirham"


class Order(models.Model):
    class Status(models.TextChoices):
        PENDING = "pending", "Pending"
        SHIPPED = "shipped", "Shipped"
        DELIVERED = "delivered", "Delivered"
        RETURNED = "returned", "Returned"
        CANCELLED = "cancelled", "Cancelled"

    merchant = models.ForeignKey(
        "accounts.Merchant", on_delete=models.PROTECT, related_name="orders"
    )
    courier = models.ForeignKey(Courier, on_delete=models.PROTECT, related_name="orders")
    tracking_number = models.CharField(max_length=64)
    customer_name = models.CharField(max_length=200)
    customer_phone = models.CharField(max_length=30, blank=True)
    city = models.CharField(max_length=100, blank=True)
    amount_due = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(ZERO)],
        help_text="Cash the courier must collect from the customer.",
    )
    currency = models.CharField(
        max_length=3, choices=Currency.choices, default=settings.DEFAULT_CURRENCY
    )
    status = models.CharField(
        max_length=16, choices=Status.choices, default=Status.PENDING, db_index=True
    )
    delivered_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]
        constraints = [
            # Tracking numbers are generated by each courier, so they are only
            # unique within that courier's namespace.
            models.UniqueConstraint(
                fields=["courier", "tracking_number"], name="uniq_tracking_per_courier"
            ),
            models.CheckConstraint(
                condition=models.Q(amount_due__gte=0), name="order_amount_due_non_negative"
            ),
        ]
        indexes = [models.Index(fields=["merchant", "courier", "status"])]

    def __str__(self) -> str:
        return f"{self.tracking_number} ({self.courier.code})"


class DeliveryAttempt(models.Model):
    class Outcome(models.TextChoices):
        DELIVERED = "delivered", "Delivered"
        NO_ANSWER = "no_answer", "Customer unreachable"
        REFUSED = "refused", "Refused by customer"
        RESCHEDULED = "rescheduled", "Rescheduled"
        RETURNED = "returned", "Returned to merchant"

    order = models.ForeignKey(Order, on_delete=models.CASCADE, related_name="attempts")
    attempted_at = models.DateTimeField(default=timezone.now)
    outcome = models.CharField(max_length=16, choices=Outcome.choices)
    note = models.CharField(max_length=255, blank=True)

    class Meta:
        ordering = ["attempted_at"]

    def __str__(self) -> str:
        return f"{self.order.tracking_number}: {self.outcome}"
